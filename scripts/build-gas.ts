// Builds dist/gas/akleg.js: the client as one plain script for Google Apps Script,
// which doesn't support ES modules. Paste it into an Apps Script project (or use clasp)
// and call `new BasisClient({ fetch: urlFetchAppFetch() })`.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import ts from 'typescript';

export function buildGasScript(): string {
  const source = readFileSync(new URL('../src/client.ts', import.meta.url), 'utf8');
  const { outputText } = ts.transpileModule(source, {
    compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.ESNext, removeComments: false },
  });
  if (/^\s*import\s/m.test(outputText)) throw new Error('src/client.ts must not have runtime imports');
  const body = outputText.replace(/^export (?=(const|function|class|async function) )/gm, '');
  if (/^export\b/m.test(body)) throw new Error('Unexpected export left in Apps Script build');
  return `// alaska-legislative-api for Google Apps Script. Generated by scripts/build-gas.ts.\n// Usage: const client = new BasisClient({ fetch: urlFetchAppFetch() });\n${body}`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  mkdirSync(new URL('../dist/gas/', import.meta.url), { recursive: true });
  writeFileSync(new URL('../dist/gas/akleg.js', import.meta.url), buildGasScript());
  console.log('wrote dist/gas/akleg.js');
}
